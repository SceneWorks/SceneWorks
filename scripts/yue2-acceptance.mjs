/**
 * Re-hash a transcription's review artifact on disk, independently of the API and the worker: the
 * manifest (`transcription.json`) must hash to the digest the job recorded and be the engine's
 * schema, and every file it lists must hash to its recorded digest.
 */
export async function verifyTranscriptionArtifact(dir, expectedManifestSha256) {
  const result = (ok, detail, extra = {}) => ({ ok, detail, files: 0, manifestSha256: null, manifest: null, ...extra });
  let bytes;
  try { bytes = await readFile(path.join(dir, TRANSCRIPTION_MANIFEST)); } catch (error) { return result(false, `${TRANSCRIPTION_MANIFEST} is unreadable: ${error.code ?? error.message}`); }
  const digest = sha256(bytes);
  if (digest !== expectedManifestSha256) return result(false, `${TRANSCRIPTION_MANIFEST} hashes to ${digest}, recorded ${expectedManifestSha256}`, { manifestSha256: digest });
  let manifest;
  try { manifest = JSON.parse(bytes.toString("utf8")); } catch (error) { return result(false, `${TRANSCRIPTION_MANIFEST} does not parse: ${error.message}`, { manifestSha256: digest }); }
  if (manifest?.schema !== TRANSCRIPTION_ARTIFACT_SCHEMA) return result(false, `${TRANSCRIPTION_MANIFEST} schema ${manifest?.schema}, expected ${TRANSCRIPTION_ARTIFACT_SCHEMA}`, { manifestSha256: digest, manifest });
  const artifacts = manifest.artifacts;
  const entries = artifacts && typeof artifacts === "object" && !Array.isArray(artifacts) ? Object.entries(artifacts) : [];
  if (!entries.length) return result(false, "the manifest lists no artifacts", { manifestSha256: digest, manifest });
  for (const [name, recorded] of entries) {
    const parts = name.split("/");
    if (!HEX64.test(recorded ?? "")) return result(false, `${name} has no SHA-256 digest`, { manifestSha256: digest, manifest, files: entries.length });
    if (path.isAbsolute(name) || parts.some((part) => !part || part === "." || part === "..")) return result(false, `${name} is not a plain relative path`, { manifestSha256: digest, manifest, files: entries.length });
    let actual;
    try { actual = await fileSha256(path.join(dir, ...parts)); } catch { return result(false, `${name} is missing`, { manifestSha256: digest, manifest, files: entries.length }); }
    if (actual !== recorded) return result(false, `${name} hashes to ${actual}, recorded ${recorded}`, { manifestSha256: digest, manifest, files: entries.length });
  }
  return result(true, `${TRANSCRIPTION_MANIFEST} + ${entries.length} artifacts re-hashed`, { manifestSha256: digest, manifest, files: entries.length });
}

