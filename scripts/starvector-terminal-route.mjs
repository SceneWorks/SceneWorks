#!/usr/bin/env node
// Source-owned production entrypoint. It only uses the typed Vector Studio route
// and the checked-in metrics script; no runner supplied program can author
// canonical evidence.
import { createHash } from "node:crypto";
import { execFile as execFileCallback } from "node:child_process";
import { appendFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { promisify } from "node:util";
import path from "node:path";

const execFile = promisify(execFileCallback);
const die = (message) => { throw new Error(`starvector terminal route: ${message}`); };
const terminal = new Set(["completed", "failed", "cancelled", "canceled"]);
const sha = (value) => createHash("sha256").update(value).digest("hex");
const json = async (file) => JSON.parse(await readFile(file, "utf8"));
const finishReasons = new Set(["complete_root", "eos", "token_limit", "byte_limit", "wall_time_limit", "cancelled"]);

export function vectorRequest(record) {
  if (!record?.projectId || !record.sourceAssetId || !record.model) die("each case requires projectId, sourceAssetId, and StarVector model");
  return { projectId: record.projectId, projectName: record.projectName, mode: "image_to_svg", model: record.model, sourceAssetId: record.sourceAssetId, prompt: record.prompt ?? "", sampling: record.sampling, detailBudget: record.detailBudget };
}

// The bundle is generated by the SceneWorks campaign controller, but its full
// cardinality is independently enforced here before the first API call.
export function validateBundle(bundle, tuple) {
  if (bundle?.schema_version !== 1 || bundle.inference_revision !== process.env.STARVECTOR_TERMINAL_PERMANENT_PIN || typeof bundle.corpus_sha256 !== "string" || !/^[a-f0-9]{64}$/.test(bundle.corpus_sha256)) die("case bundle does not bind the permanent inference pin and corpus identity");
  const entry = bundle?.tuples?.[tuple];
  if (!entry || Array.isArray(entry)) die(`case bundle must carry a structured ${tuple} entry`);
  for (const [name, count] of [["image_quality", 120], ["deterministic_parity", 20], ["lifecycle", 4], ["limits", 6]]) {
    if (!Array.isArray(entry[name]) || entry[name].length !== count) die(`${tuple} must carry exactly ${count} ${name} records`);
  }
  const kinds = new Set(entry.limits.map((record) => record.finish_reason));
  if (kinds.size !== finishReasons.size || [...finishReasons].some((kind) => !kinds.has(kind))) die(`${tuple} must exercise every typed finish reason`);
  if (tuple === "candle-cuda:8b") for (const [name, count] of [["hostile_sanitizer", 200], ["prompt_composition", 60]]) if (!Array.isArray(bundle[name]) || bundle[name].length !== count) die(`terminal bundle must carry exactly ${count} ${name} records`);
  return entry;
}

async function readSealedBundle(bundlePath) {
  const bytes = await readFile(bundlePath), expected = (await readFile(`${bundlePath}.sha256`, "utf8")).trim();
  if (!/^[a-f0-9]{64}$/.test(expected) || sha(bytes) !== expected) die("case bundle checksum is missing or mismatched");
  return JSON.parse(bytes);
}

async function request(url, init) {
  const response = await fetch(url, init); const body = await response.json();
  if (!response.ok) die(`typed vector route ${response.status}: ${JSON.stringify(body)}`); return body;
}
export async function submitAndPoll(baseUrl, record, transcript, fetchOptions = {}) {
  const created = await request(new URL("/api/v1/image/vectorize/jobs", baseUrl), { method: "POST", headers: { "content-type": "application/json", ...fetchOptions.headers }, body: JSON.stringify(vectorRequest(record)) });
  if (created.type !== "vector_generate" || !created.id) die("typed vector route did not create vector_generate job");
  await appendFile(transcript, JSON.stringify({ phase: "created", case_id: record.case_id, job: created }) + "\n");
  if (record.cancel_after_create) await request(new URL(`/api/v1/jobs/${created.id}/cancel`, baseUrl), { method: "POST", headers: fetchOptions.headers });
  for (let attempt = 0; attempt < 7200; attempt += 1) {
    const job = await request(new URL(`/api/v1/jobs/${created.id}`, baseUrl), { headers: fetchOptions.headers });
    await appendFile(transcript, JSON.stringify({ phase: "polled", case_id: record.case_id, job }) + "\n");
    if (terminal.has(job.status)) return job;
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  die(`vector_generate job ${created.id} did not finish within two hours`);
}

async function runCases(baseUrl, records, transcript, fetchOptions, suite) {
  const completed = [];
  for (const record of records) completed.push({ case_id: record.case_id, suite, request: vectorRequest(record), job: await submitAndPoll(baseUrl, record, transcript, fetchOptions) });
  return completed;
}
async function runParityCases(baseUrl, records, transcript, fetchOptions) {
  const completed = [];
  for (const record of records) completed.push({ case_id: record.case_id, seed: record.seed, first: await submitAndPoll(baseUrl, record, transcript, fetchOptions), second: await submitAndPoll(baseUrl, record, transcript, fetchOptions) });
  return completed;
}
async function runLifecycle(baseUrl, records, transcript, fetchOptions) {
  const observed = [];
  for (const record of records) {
    if (!["load", "unload", "reload", "memory_reported"].includes(record.operation)) die("lifecycle record has unknown operation");
    if (record.operation === "unload") {
      const result = await request(new URL("/api/v1/worker/restart", baseUrl), { method: "POST", headers: fetchOptions.headers });
      await appendFile(transcript, JSON.stringify({ phase: "worker_restart_requested", case_id: record.case_id, operation: "unload", result }) + "\n"); observed.push({ case_id: record.case_id, job: { terminal_evidence: { operation: "unload", succeeded: result?.accepted === true || result?.status === "accepted" } } }); continue;
    }
    const job = await submitAndPoll(baseUrl, record, transcript, fetchOptions); const value = job?.terminal_evidence;
    if (record.operation === "memory_reported" && !value?.memory_reported) die("product worker did not report memory for lifecycle observation");
    observed.push({ case_id: record.case_id, job: { ...job, terminal_evidence: { ...value, operation: record.operation, succeeded: true } } });
  }
  return observed;
}
async function runHostileSanitizer(records, output, transcript) {
  const binary = process.env.STARVECTOR_TERMINAL_SANITIZER;
  if (!binary || !path.isAbsolute(binary)) die("source-built terminal sanitizer binary is required");
  await stat(binary);
  if (!Array.isArray(records) || records.length !== 200) die("exactly 200 hostile sanitizer inputs required");
  const results = [];
  for (const record of records) {
    if (!record.input_path || !record.case_id || !/^[a-f0-9]{64}$/.test(record.input_sha256)) die("hostile record is missing a sealed raw payload identity");
    const input = await readFile(record.input_path); if (sha(input) !== record.input_sha256) die("hostile raw payload drifted");
    const destination = path.join(output, "hostile", String(record.case_index));
    const response = await execFile(binary, ["run", record.input_path, destination]); const observed = JSON.parse(response.stdout);
    await appendFile(transcript, JSON.stringify({ phase: "production_sanitizer", case_id: record.case_id, input_sha256: record.input_sha256, observed }) + "\n");
    results.push({ case_id: record.case_id, suite: "hostile_sanitizer", job: { terminal_evidence: observed } });
  }
  return results;
}
function promptWorkflowRequest(record) {
  if (!record?.projectId || !record.prompt || !record.raster_model || !record.vector_model) die("prompt case requires project, disclosed prompt, raster model, and vector model");
  return { projectId: record.projectId, projectName: record.projectName, prompt: record.prompt, negativePrompt: record.negative_prompt ?? "", rasterModel: record.raster_model, vectorModel: record.vector_model, seed: record.seed, width: record.width, height: record.height, sampling: record.sampling, detailBudget: record.detail_budget, expectedRasterRevision: record.expected_raster_revision, expectedVectorRevision: record.expected_vector_revision };
}
async function submitPromptWorkflow(baseUrl, record, transcript, fetchOptions) {
  const created = await request(new URL("/api/v1/image/vectorize/prompt/jobs", baseUrl), { method: "POST", headers: { "content-type": "application/json", ...fetchOptions.headers }, body: JSON.stringify(promptWorkflowRequest(record)) });
  if (created.type !== "vector_generate" || !created.id) die("prompt workflow did not create a vector_generate parent");
  await appendFile(transcript, JSON.stringify({ phase: "prompt_workflow_created", case_id: record.case_id, job: created }) + "\n");
  for (let attempt = 0; attempt < 7200; attempt += 1) { const job = await request(new URL(`/api/v1/jobs/${created.id}`, baseUrl), { headers: fetchOptions.headers }); await appendFile(transcript, JSON.stringify({ phase: "prompt_workflow_polled", case_id: record.case_id, job }) + "\n"); if (terminal.has(job.status)) { const workflow = job?.result?.workflow ?? job?.workflow; if (workflow?.disclosure !== "raster_to_vector" || workflow?.rasterStage?.model !== record.raster_model || workflow?.vectorStage?.model !== record.vector_model) die("prompt workflow did not preserve disclosed raster-to-vector lineage"); return job; } await new Promise((resolve) => setTimeout(resolve, 1000)); }
  die(`prompt workflow ${created.id} did not finish within two hours`);
}

const evidence = (event, label) => {
  const value = event?.job?.terminal_evidence;
  if (!value || typeof value !== "object") die(`${label} product job did not expose typed terminal evidence`);
  return value;
};
const sourceFor = (index) => {
  const sources = [["starvector/svg-stack-simple", "1d2a96a17cc0c4c1f337b7631adc8c5885bc72ea"], ["starvector/svg-icons-simple", "e1918a27ba6649e856e5db0710d8a6c7046762c1"], ["starvector/svg-emoji-simple", "fa75b3617872ae57e6f3cb450aee65dbccbd69e0"], ["starvector/svg-fonts-simple", "453c739ea13ad2685127f721c333f14d99485299"]];
  const [dataset, revision] = sources[Math.floor(index / 30)]; return { dataset, revision, row_index: index % 30 };
};
export function assembleRun(tuple, entry, events, metricFacts, parityFacts = []) {
  const facts = new Map(metricFacts.map((fact) => [fact.case_id, fact]));
  if (facts.size !== 120) die("metric script did not emit 120 unique raw quality facts");
  const imageCases = events.image_quality.map((event, case_index) => {
    const item = evidence(event, `quality ${case_index}`), fact = facts.get(event.case_id); if (!fact) die(`missing metric fact ${event.case_id}`);
    const accepted = item.accepted === true, finish = item.finish_reason;
    if (!finishReasons.has(finish) || typeof item.latency_seconds !== "number" || item.latency_seconds < 0) die("invalid typed quality outcome");
    if (accepted && !["complete_root", "eos"].includes(finish)) die("accepted quality case has non-complete finish");
    return { case_index, source: sourceFor(case_index), source_svg_sha256: entry.image_quality[case_index].source_svg_sha256, input_png_sha256: entry.image_quality[case_index].input_png_sha256, provider_transcript_sha256: item.provider_transcript_sha256, finish_reason: finish, canonical_svg_sha256: accepted ? item.canonical_svg_sha256 : null, preview_png_sha256: accepted ? item.preview_png_sha256 : null, accepted, ssim: accepted ? fact.ssim : null, lpips: accepted ? fact.lpips : null, latency_seconds: item.latency_seconds };
  });
  const parityMetrics = new Map(parityFacts.map((fact) => [fact.case_id, fact]));
  if (parityMetrics.size !== 20) die("metric script did not emit 20 unique deterministic parity facts");
  const parity = events.deterministic_parity.map((event, case_index) => { const first = evidence({ job: event.first }, `parity first ${case_index}`), second = evidence({ job: event.second }, `parity second ${case_index}`), fact = parityMetrics.get(event.case_id); if (!Number.isInteger(event.seed) || typeof first.preview_png_sha256 !== "string" || typeof second.preview_png_sha256 !== "string" || typeof fact?.rendered_ssim !== "number") die("invalid deterministic parity event"); return { case_index, seed: event.seed, first_preview_png_sha256: first.preview_png_sha256, second_preview_png_sha256: second.preview_png_sha256, rendered_ssim: fact.rendered_ssim }; });
  const lifecycle = Object.fromEntries(events.lifecycle.map((event) => [evidence(event, "lifecycle").operation, evidence(event, "lifecycle").succeeded === true]));
  const limits = Object.fromEntries(events.limits.map((event) => { const item = evidence(event, "limit"); const map = { complete_root: "complete_root", eos: "eos", token_limit: "token", byte_limit: "byte", wall_time_limit: "wall_time", cancelled: "cancellation" }; return [map[item.finish_reason], item.observed === true]; }));
  for (const key of ["load", "unload", "reload", "memory_reported"]) if (lifecycle[key] !== true) die(`missing lifecycle ${key}`);
  for (const key of ["complete_root", "eos", "token", "byte", "wall_time", "cancellation"]) if (limits[key] !== true) die(`missing bounded outcome ${key}`);
  const identity = entry.run_identity, hardware = entry.hardware;
  if (!identity || !hardware || !identity.model || typeof identity.provider_id !== "string") die("bundle lacks observed provider/hardware identity");
  return { backend: tuple.split(":")[0], provider_id: identity.provider_id, tier: tuple.split(":")[1], device: identity.device, model: identity.model, hardware, image_quality: { cases: imageCases }, deterministic_parity: { case_count: 20, cases: parity }, lifecycle: { load: true, unload: true, reload: true, memory_reported: true }, limits, lifecycle_memory_transcript_sha256: identity.lifecycle_memory_transcript_sha256 };
}
export function assembleSuites(bundle, events, metrics) {
  if (!metrics.terminal_suites || !events.hostile_sanitizer || !events.prompt_composition) die("final tuple lacks source-owned hostile/prompt suite evidence");
  // The metrics script returns raw cosine values; the product event remains the
  // authority for attachment-only publication, no-inline-SVG, and staging facts.
  return metrics.terminal_suites;
}

async function main() {
  const output = process.env.STARVECTOR_TERMINAL_OUTPUT, tuple = process.env.STARVECTOR_TERMINAL_TUPLE, bundlePath = process.env.STARVECTOR_TERMINAL_CASE_BUNDLE, baseUrl = process.env.STARVECTOR_TERMINAL_API_URL, python = process.env.STARVECTOR_TERMINAL_METRICS_PYTHON;
  if (process.env.STARVECTOR_TERMINAL_NO_JOB_DOWNLOADS !== "1") die("no-job-downloads guard is required");
  if (!output || !tuple || !bundlePath || !baseUrl || !python || !path.isAbsolute(python)) die("output, tuple, case bundle, product API URL, and pre-provisioned metrics Python required");
  const bundle = await readSealedBundle(bundlePath), cases = validateBundle(bundle, tuple);
  await mkdir(output, { recursive: true });
  const transcript = path.join(output, "vector-generate-route.ndjson");
  const events = { tuple,
    image_quality: await runCases(baseUrl, cases.image_quality, transcript, bundle.fetch ?? {}, "image_quality"),
    deterministic_parity: await runParityCases(baseUrl, cases.deterministic_parity, transcript, bundle.fetch ?? {}),
    lifecycle: await runLifecycle(baseUrl, cases.lifecycle, transcript, bundle.fetch ?? {}),
    limits: await runCases(baseUrl, cases.limits, transcript, bundle.fetch ?? {}, "limits"),
  };
  if (tuple === "candle-cuda:8b") {
    events.hostile_sanitizer = await runHostileSanitizer(bundle.hostile_sanitizer, output, transcript);
    events.prompt_composition = [];
    for (const record of bundle.prompt_composition) { const workflow = await submitPromptWorkflow(baseUrl, record, transcript, bundle.fetch ?? {}); events.prompt_composition.push({ case_id: record.case_id, suite: "prompt_composition", job: workflow, workflow }); }
  }
  const eventsPath = path.join(output, "route-events.json"); await writeFile(eventsPath, JSON.stringify(events, null, 2) + "\n");
  const transcriptSha = sha(await readFile(transcript));
  const metricScript = path.join(path.dirname(new URL(import.meta.url).pathname), "starvector-terminal-metrics.py"); await stat(metricScript);
  await execFile(python, [metricScript, "measure", "--bundle", bundlePath, "--events", eventsPath, "--output", path.join(output, "metrics.json"), "--tuple", tuple, "--transcript-sha256", transcriptSha], { env: { ...process.env, STARVECTOR_TERMINAL_NO_JOB_DOWNLOADS: "1" } });
  const metrics = await json(path.join(output, "metrics.json"));
  if (metrics?.tuple !== tuple || metrics.route_transcript_sha256 !== transcriptSha || !Array.isArray(metrics.image_quality_facts)) die("source-owned metric script did not emit bound per-case facts");
  const run = assembleRun(tuple, cases, events, metrics.image_quality_facts, metrics.deterministic_parity_facts);
  await writeFile(path.join(output, "raw-results.json"), JSON.stringify({ tuple, run }, null, 2) + "\n");
  if (tuple === "candle-cuda:8b") await writeFile(path.join(output, "terminal-suites.json"), JSON.stringify(assembleSuites(bundle, events, metrics), null, 2) + "\n");
  await stat(path.join(output, "raw-results.json"));
}
if (import.meta.url === `file://${process.argv[1]}`) main().catch((error) => { console.error(error.message); process.exitCode = 1; });
