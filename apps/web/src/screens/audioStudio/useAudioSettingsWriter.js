import { useStudioSettingsWriter } from "../../hooks/useStudioSettings.js";

// Extracted from AudioStudio along its existing concern boundary.
export function useAudioSettingsWriter({
  activeProject,
  mode,
  model,
  prompt,
  script,
  voice,
  language,
  editMode,
  targetDurationSecs,
  seed,
  guidance,
  schedulerShift,
  steps,
  bpm,
  musicalKey,
  lyrics,
  negativePrompt,
  sourceAudioAssetId,
  editRegionStartSecs,
  editRegionEndSecs,
  editStrength,
  referenceAudioAssetId,
  matchStrength,
  yueSections,
  genreTags,
  segments,
  maxNewTokensPerSegment,
  repetitionPenalty,
  guidanceEnabled,
  songGuidance,
  outputLimiter,
  iclMode,
  iclReferenceAssetId,
  iclVocalAssetId,
  iclInstrumentalAssetId,
  iclStartSecs,
  iclEndSecs,
  advancedOpen,
  surface,
  preferencesHydrated,
  audioModels
}) {
  // Per-workspace stickiness (sc-11964 pattern). Suppressed until the audio catalog has loaded so a
  // transient default can't overwrite the restored snapshot mid-settle.
  useStudioSettingsWriter(
    "audio",
    activeProject?.id ?? null,
    {
      mode,
      model,
      prompt,
      script,
      voice,
      language,
      editMode,
      targetDurationSecs,
      seed,
      guidance,
      schedulerShift,
      steps,
      bpm,
      musicalKey,
      lyrics,
      negativePrompt,
      sourceAudioAssetId,
      editRegionStartSecs,
      editRegionEndSecs,
      editStrength,
      referenceAudioAssetId,
      matchStrength,
      yueSections,
      genreTags,
      segments,
      maxNewTokensPerSegment,
      repetitionPenalty,
      guidanceEnabled,
      songGuidance,
      outputLimiter,
      iclMode,
      iclReferenceAssetId,
      iclVocalAssetId,
      iclInstrumentalAssetId,
      iclStartSecs,
      iclEndSecs,
      advancedOpen,
      songLab: surface === "yue2",
    },
    // Plus ui-preferences hydration (sc-15425) — see the same gate in ImageStudio.
    preferencesHydrated && audioModels.length > 0,
  );
}
