import { ltx25VideoModelId, VIDEO_PRESET_MODES } from "./videoTierHelpers.js";
import { finiteNumberOrUndefined } from "../../presetUtils.js";
import { useSavePreset } from "../../components/generationStudio.jsx";
import { useStudioSettingsWriter } from "../../hooks/useStudioSettings.js";
import { restoreVedaSettings, vedaAdvancedSettings } from "../../vedaControls.js";

// Extracted from VideoStudio along its existing concern boundary.
export function useVideoPresetState({
  saved,
  selectedPreset,
  setSelectedPresetId,
  presets,
  mode,
  model,
  selectedLoras,
  effectiveLoraWeight,
  createPreset,
  activeProject,
  setMode,
  setPrompt,
  setNegativePrompt,
  setResolution,
  setDuration,
  setFps,
  setQuality,
  setGuidanceOverride,
  setStepsOverride,
  setVeda,
  setSampler,
  setScheduler,
  setSchedulerShift,
  setPrecision,
  setQuantization,
  setLtxPipeline,
  setDistilledVariant,
  setTransformerVariant,
  setVaeDecoder,
  setAutoDuration,
  setAutoDurationMinSeconds,
  setAutoDurationMaxSeconds,
  setTemporalUpsampleRounds,
  setEnhancePrompt,
  setTextEncoderModel,
  setMotion,
  setLtxVideoCfg,
  setLtxVideoStg,
  setLtxVideoRescale,
  prompt,
  negativePrompt,
  resolution,
  duration,
  fps,
  quality,
  guidanceOverride,
  veda,
  stepsOverride,
  sampler,
  scheduler,
  schedulerShift,
  schedulerShiftExplicit,
  precision,
  quantization,
  ltxPipeline,
  distilledVariant,
  transformerVariant,
  vaeDecoder,
  autoDuration,
  autoDurationMinSeconds,
  autoDurationMaxSeconds,
  temporalUpsampleRounds,
  supportsPromptEnhancement,
  enhancePrompt,
  supportsTextEncoderSelection,
  selectedTextEncoderModel,
  motion,
  showsLegacyLtxGuidanceControls,
  ltxVideoCfg,
  ltxVideoStg,
  ltxVideoRescale,
  styleId,
  appearance,
  textEncoderModel,
  advancedOpen,
  selectedLoraIds,
  loraWeights,
  seed,
  selectedPresetId,
  generalStackIds,
  lightning,
  turboSeededModels,
  videoConditioningStrength,
  bridgeRightVideoConditioningStrength,
  fitMode,
  sourceAssetId,
  sourceAssetOrigin,
  expectedImportedModelRef,
  lastFrameAssetId,
  sourceClipAssetId,
  bridgeRightClipAssetId,
  referenceAssetIds,
  referenceAudioAssetIds,
  sourceClipAssetIds,
  referenceClipAssetId,
  characterId,
  characterLookId,
  personTrackId,
  replacementMode,
  selectedDetectionId,
  trackName,
  preferencesHydrated,
  videoModels
}) {
  // Save-as-Preset + the preset-default hydrate pass (sc-8937 — shared with the Image
  // studio via useSavePreset). The [key, setter] pairs are restored through the
  // remember/clear snapshot machinery, so switching to None (or another preset) puts
  // the user's prior value back. Only keys the preset carries are applied, so older
  // presets keep working and full-snapshot presets restore the prompt, cfg, sampler,
  // and the native LTX guidance knobs. The model is intentionally absent — presets
  // never switch the model.
  const {
    presetName,
    setPresetName,
    presetScope,
    setPresetScope,
    savingPreset,
    presetSaveMessage,
    setPresetSaveMessage,
    handleSaveAsPreset,
  } = useSavePreset({
    saved,
    selectedPreset,
    setSelectedPresetId,
    presets,
    mode,
    model,
    selectedLoras,
    effectiveLoraWeight,
    createPreset,
    activeProject,
    setMode,
    presetDefaultFields: [
      ["prompt", setPrompt],
      ["negativePrompt", setNegativePrompt],
      ["resolution", setResolution],
      ["duration", setDuration],
      ["fps", setFps],
      ["quality", setQuality],
      ["guidanceScale", setGuidanceOverride],
      ["steps", setStepsOverride],
      ["veda", (value) => setVeda(restoreVedaSettings({ veda: value }))],
      ["sampler", setSampler],
      ["scheduler", setScheduler],
      ["schedulerShift", setSchedulerShift],
      ["precision", setPrecision],
      ["quantization", setQuantization],
      ["ltxPipeline", setLtxPipeline],
      ["distilledVariant", setDistilledVariant],
      ["transformerVariant", setTransformerVariant],
      ["vaeDecoder", setVaeDecoder],
      ["autoDuration", setAutoDuration],
      ["autoDurationMinSeconds", setAutoDurationMinSeconds],
      ["autoDurationMaxSeconds", setAutoDurationMaxSeconds],
      ["temporalUpsampleRounds", setTemporalUpsampleRounds],
      ["enhancePrompt", setEnhancePrompt],
      ["textEncoderModel", setTextEncoderModel],
      ["motion", setMotion],
      ["videoCfgGuidanceScale", setLtxVideoCfg],
      ["videoStgGuidanceScale", setLtxVideoStg],
      ["videoRescaleScale", setLtxVideoRescale],
    ],
    // Restore the saved sub-mode ("type") when it's a generatable video workflow.
    modeIsPresetable: (savedMode) => VIDEO_PRESET_MODES.includes(savedMode),
    // Video gates saving to the presetable modes; blocks the rest with a message.
    extraSaveGuard: () =>
      VIDEO_PRESET_MODES.includes(mode)
        ? null
        : "Switch to Image, Text, or First/Last mode to save a preset.",
    buildDefaults: () => ({
      prompt,
      negativePrompt,
      resolution,
      duration,
      fps,
      quality,
      mode,
      guidanceScale: finiteNumberOrUndefined(guidanceOverride),
      ...vedaAdvancedSettings(veda),
      steps: finiteNumberOrUndefined(stepsOverride),
      sampler,
      scheduler,
      schedulerShift: finiteNumberOrUndefined(schedulerShift),
      precision,
      quantization,
      ltxPipeline,
      distilledVariant,
      transformerVariant,
      ...(model === ltx25VideoModelId
        ? {
            vaeDecoder,
            autoDuration,
            autoDurationMinSeconds,
            autoDurationMaxSeconds,
            temporalUpsampleRounds,
          }
        : {}),
      ...(supportsPromptEnhancement ? { enhancePrompt } : {}),
      ...(supportsTextEncoderSelection ? { textEncoderModel: selectedTextEncoderModel } : {}),
      motion,
      ...(showsLegacyLtxGuidanceControls
        ? {
            videoCfgGuidanceScale: finiteNumberOrUndefined(ltxVideoCfg),
            videoStgGuidanceScale: finiteNumberOrUndefined(ltxVideoStg),
            videoRescaleScale: finiteNumberOrUndefined(ltxVideoRescale),
          }
        : {}),
    }),
  });

  useStudioSettingsWriter("video", activeProject?.id ?? null, {
    veda,
    motion,
    mode,
    prompt,
    styleId,
    appearance,
    quality,
    ltxPipeline,
    distilledVariant,
    transformerVariant,
    vaeDecoder,
    autoDuration,
    autoDurationMinSeconds,
    autoDurationMaxSeconds,
    temporalUpsampleRounds,
    precision,
    enhancePrompt,
    textEncoderModel,
    quantization,
    advancedOpen,
    selectedLoraIds,
    loraWeights,
    model,
    duration,
    resolution,
    fps,
    seed,
    negativePrompt,
    selectedPresetId,
    generalStackIds,
    sampler,
    scheduler,
    schedulerShift,
    schedulerShiftExplicit,
    steps: stepsOverride,
    guidanceScale: guidanceOverride,
    lightning,
    // The MiniMax-H3 turbo default-on one-shot marker (sc-18727). The SELECTION itself already
    // persists through `selectedLoraIds`; this records only that the seed has fired, so a
    // deliberate "Off" is not re-seeded on the next mount or the next relaunch.
    turboSeededModels,
    videoCfgGuidanceScale: ltxVideoCfg,
    videoStgGuidanceScale: ltxVideoStg,
    videoRescaleScale: ltxVideoRescale,
    videoConditioningStrength,
    bridgeRightVideoConditioningStrength,
    fitMode,
    // User asset/reference/character/person-track selections (sc-11964). These are USER choices,
    // not model defaults, so they persist here and restore across a full restart — kept out of the
    // defaults-reset path. Restore-validation (above) drops any id whose asset/track is gone.
    sourceAssetId,
    // How that first frame was chosen (sc-26687): "ambient" = the app's current selection,
    // adopted on the user's behalf; "explicit" = the user's own pick. Only an explicit one may
    // ride along in an imported last-only request.
    sourceAssetOrigin,
    expectedImportedModelRef,
    lastFrameAssetId,
    sourceClipAssetId,
    bridgeRightClipAssetId,
    referenceAssetIds,
    referenceAudioAssetIds,
    sourceClipAssetIds,
    referenceClipAssetId,
    characterId,
    characterLookId,
    personTrackId,
    replacementMode,
    selectedDetectionId,
    trackName,
  },
  // Suppress the live writer until the video catalog has loaded (sc-11962), so a transient
  // defaults-reset during the restart-restore/settle window can't overwrite the restored
  // snapshot before the async catalogs settle.
  // Plus ui-preferences hydration (sc-15425) — see the same gate in ImageStudio.
  preferencesHydrated && videoModels.length > 0);
  return { presetName, setPresetName, presetScope, setPresetScope, savingPreset, presetSaveMessage, setPresetSaveMessage, handleSaveAsPreset };
}
